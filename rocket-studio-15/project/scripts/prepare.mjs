#!/usr/bin/env node
/** Compile one timeline, render props and matching original audio stems. */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {compileTimeline} from '../src/motion.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const configIndex = args.indexOf('--config');
const configPath = configIndex >= 0 ? path.resolve(args[configIndex + 1]) : path.join(root, 'project.json');
const source = JSON.parse(fs.readFileSync(configPath, 'utf8'));
const config = source.config || source;
const timeline = compileTimeline(config);
fs.writeFileSync(path.join(root, 'timeline.json'), JSON.stringify(timeline, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'render-props.json'), JSON.stringify({
  config,
  audioEnabled: source.audioEnabled ?? true,
  masterVolume: source.masterVolume ?? 1,
}, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'src/preparedAudio.ts'),
  '/** Generated by scripts/prepare.mjs. The matching WAV is in public/audio. */\n' +
  'export const preparedTimelineSignature = ' + JSON.stringify(JSON.stringify(timeline)) + ';\n');
const audio = spawnSync(process.execPath, [path.join(root, 'scripts/build-audio.mjs'), path.join(root, 'timeline.json')], {
  stdio: 'inherit', cwd: root,
});
if (audio.status !== 0) process.exit(audio.status || 1);
console.log(`Prepared ${timeline.frames} frames / ${timeline.duration}s from ${configPath}`);
